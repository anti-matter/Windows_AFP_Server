#include "stdafx.h"
#include "AutoLock.h"

//---------------------------------------------------------------------
//---------------------------------------------------------------------
AutoLock::AutoLock(CRITICAL_SECTION* toLock)
    : _cs(toLock)
{
    this->Lock();
}


//---------------------------------------------------------------------
//---------------------------------------------------------------------
AutoLock::~AutoLock()
{
    this->Unlock();
}

//---------------------------------------------------------------------
//---------------------------------------------------------------------
void AutoLock::Lock() const
{
    EnterCriticalSection(_cs);
}

//---------------------------------------------------------------------
//---------------------------------------------------------------------
void AutoLock::Unlock() const
{
    LeaveCriticalSection(_cs);
}

